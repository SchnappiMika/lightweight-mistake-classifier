def build_dim(scheme_name: str, key: str, name: str, spec: Dict[str, Dict],
              enabled: bool = True) -> Dict:
    labels: List[Dict] = []
    for lname, cfg in spec.items():
        labels.append({
            "id": sid("lb", scheme_name, key, lname),
            "name": lname,
            "dim": key,
            "keywords": cfg["kw"],
            "keyword_weights": {},
            "samples": cfg.get("s", []),
            "weight_override": {},
            "prior": 1.0,
            "note": "",
        })
    return {"key": key, "name": name, "enabled": enabled, "labels": labels}


def simple_spec(kw_map: Dict[str, List[str]], sample_map: Dict[str, List[str]]) -> Dict[str, Dict]:
    return {k: {"kw": v, "s": sample_map.get(k, [])} for k, v in kw_map.items()}


def build_scheme(name: str, subject: str, desc: str, knowledge: Dict[str, Dict]) -> Dict:
    dims = [build_dim(name, "knowledge", "知识点", knowledge)] if knowledge else []
    dims += [
        build_dim(name, "error_type", "错误类型", simple_spec(ERROR_TYPES, ERROR_SAMPLES)),
        build_dim(name, "difficulty", "题目难度", simple_spec(DIFFICULTIES, DIFF_SAMPLES)),
        build_dim(name, "priority", "复习优先级", simple_spec(PRIORITIES, PRIO_SAMPLES)),
    ]
    return {
        "id": sid("sc", name),
        "name": name,
        "subject": subject,
        "description": desc,
        "builtin": True,
        "revision": 0,
        "dims": dims,
    }


