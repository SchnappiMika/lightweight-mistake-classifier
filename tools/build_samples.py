    rows: List[Dict] = []
    for text, subject, qtype, note, gold in D:
        rows.append({"题干": text, "学科": subject, "题型": qtype,
                     "标注": note, "媒体路径": "", "标准知识点": gold})

    # 1) Excel 批量导入示例（不含"标准知识点"列，模拟真实导入场景）
