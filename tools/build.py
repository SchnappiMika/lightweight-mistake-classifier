# -*- coding: utf-8 -*-
"""Build the desktop app and a separate media worker into one portable folder.

On Windows with a Chinese project path, use an ASCII subst drive for the build
interpreter: Qt 5.15's QLibraryInfo otherwise returns a lossy plugin path.
No user workspace or external model cache is bundled. The executables include
their Python runtime; the target computer does not need a Python installation.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent.parent
ROOT = Path.cwd() if Path.cwd().samefile(_HERE) else _HERE


def build_spec(onedir: bool = True) -> Path:
    """Generate independent GUI/media analyses, then collect one directory.

PyInstaller on Windows imports all analysed packages in one DLL discovery
process. Importing Qt and ONNX Runtime in that process crashes this environment.
Separate analyses preserve the same native-library isolation as runtime workers.
"""
    if not onedir:
        raise ValueError("媒体工作进程需要目录版发布，请使用 --onedir。")
    specification = '''# -*- mode: python ; coding: utf-8 -*-
# Generated by tools/build.py. GUI and media worker intentionally have independent analyses.
from pathlib import Path
from PyInstaller.utils.hooks import collect_data_files, collect_dynamic_libs, copy_metadata, get_package_paths

common_excludes = [
    'torch', 'torchvision', 'torchaudio', 'pix2tex', 'paddle', 'paddleocr',
    'paddlepaddle', 'whisper', 'transformers', 'tensorflow', 'tensorrt', 'openvino',
    'pytest', 'matplotlib', 'notebook', 'IPython', 'tkinter', 'nltk',
]
gui = Analysis(
    ['main.py'], pathex=['.'], binaries=[],
    datas=[('resources', 'resources'), ('samples/sample_questions.txt', 'samples'),
           ('samples/sample_questions.xlsx', 'samples')],
    hiddenimports=['PyQt5.QtSvg', 'PyQt5.QtPrintSupport', 'jieba', 'jieba.finalseg',
                   'openpyxl.cell._writer'],
    hookspath=['tools/hooks'],
    excludes=common_excludes + ['rapidocr', 'onnxruntime', 'faster_whisper', 'ctranslate2',
                               'av', 'cv2', 'PyQt5.QtWebEngineWidgets'],
    noarchive=False,
)
gui_pyz = PYZ(gui.pure)
gui_exe = EXE(gui_pyz, gui.scripts, [], exclude_binaries=True, name='错题自动分类',
              console=False, debug=False, strip=False, upx=False)

media_datas = (collect_data_files('rapidocr') + collect_data_files('faster_whisper')
               + copy_metadata('rapidocr') + copy_metadata('faster-whisper')
               + copy_metadata('ctranslate2') + copy_metadata('huggingface-hub')
               + copy_metadata('tokenizers'))
media_binaries = collect_dynamic_libs('ctranslate2')
media = Analysis(
    ['tools/media_worker_entry.py'], pathex=['.'], binaries=media_binaries,
    datas=media_datas,
    hiddenimports=['rapidocr.main', 'rapidocr.inference_engine.onnxruntime',
                   'faster_whisper', 'ctranslate2', 'onnxruntime', 'av'],
    hookspath=['tools/hooks'],
    excludes=common_excludes + ['PyQt5', 'PyQt6', 'PySide2', 'PySide6', 'app.ui',
                               'rapidocr.inference_engine.pytorch',
                               'rapidocr.inference_engine.paddle',
                               'rapidocr.inference_engine.tensorrt',
                               'rapidocr.inference_engine.openvino',
                               'rapidocr.inference_engine.mnn',
                               'ctranslate2.converters', 'ctranslate2.specs',
                               'sklearn', 'pandas', 'scipy'],
    noarchive=False,
)
media_pyz = PYZ(media.pure)
media_exe = EXE(media_pyz, media.scripts, [], exclude_binaries=True, name='media_worker',
                console=False, debug=False, strip=False, upx=False)

# Qt 5.15 ships an older MSVCP140.dll (14.26). Windows' dependency scan can
# accidentally select it for ONNX Runtime/CTranslate2, which then crash with an
# access violation at import. Prefer the current MSVC runtime already shipped
# by the installed scikit-learn wheel; use one version in all collected locations.
import sys
if sys.platform == 'win32':
    _, sklearn_directory = get_package_paths('sklearn')
    runtime = Path(sklearn_directory) / '.libs' / 'msvcp140.dll'
    if not runtime.is_file():
        raise RuntimeError('The scikit-learn MSVC redistributable is missing: ' + str(runtime))
    for analysis in (gui, media):
        analysis.binaries = [(destination, str(runtime), kind)
                             if Path(destination.replace('\\\\', '/')).name.lower() == 'msvcp140.dll'
                             else (destination, source, kind)
                             for destination, source, kind in analysis.binaries]
    media.binaries.insert(0, ('MSVCP140.dll', str(runtime), 'BINARY'))
coll = COLLECT(gui_exe, media_exe, gui.binaries, gui.datas, media.binaries, media.datas,
               strip=False, upx=False, name='错题自动分类')
'''
    if sys.platform == "darwin":
        specification += "\napp = BUNDLE(coll, name='错题自动分类.app', bundle_identifier='edu.student.mistake.classifier')\n"
    path = ROOT / "mistake_classifier.spec"
    path.write_text(specification, encoding="utf-8")
    return path


def validate_build_environment() -> None:
    """Fail early when Qt's build-time plugin lookup is invalid."""
    from PyQt5.QtCore import QLibraryInfo
    plugins = Path(QLibraryInfo.location(QLibraryInfo.PluginsPath))
    if not plugins.is_dir():
        raise RuntimeError("Qt 构建插件目录无法解析：{}。请从 ASCII 路径的 subst 映射盘运行项目解释器。".format(plugins))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="构建含独立识别工作进程的目录版发布包")
    parser.add_argument("--onedir", action="store_true", help="目录版（当前默认且唯一受验证的模式）")
    parser.add_argument("--clean", action="store_true", help="仅清理项目的 PyInstaller 构建缓存")
    parser.add_argument("--spec-only", action="store_true", help="只生成 spec，不运行构建")
    args = parser.parse_args(argv)
    spec = build_spec(True)
    if args.spec_only:
        print("已生成 {}".format(spec))
        return 0
    try:
        import PyInstaller
        validate_build_environment()
    except (ImportError, RuntimeError) as exc:
        print(str(exc))
        return 1
    command = [sys.executable, "-m", "PyInstaller", "--noconfirm"]
    if args.clean:
        command.append("--clean")
    command.append(spec.name)
    result = subprocess.call(command, cwd=str(ROOT))
    if result == 0:
        target = ROOT / "dist" / "错题自动分类"
        for name in ("README.md", "LICENSE", "开始使用.md"):
            shutil.copy2(ROOT / name, target / name)
        (target / "release-info.json").write_text(json.dumps({
            "python": sys.version, "pyinstaller": PyInstaller.__version__,
            "platform": sys.platform, "layout": "onedir", "workers": ["media_worker"],
            "helper_capabilities": ["image", "audio", "formula_bridge"],
            "formula_runtime": "Optional external pix2tex runtime; torch and pix2tex are not bundled into the GUI/helper",
            "bundled_model": "RapidOCR installed models; local Whisper base is staged separately after build",
            "clean_machine_verified": False, "macos_verified": False,
        }, ensure_ascii=False, indent=2), encoding="utf-8")
        print("构建完成：{}".format(target))
    return result


if __name__ == "__main__":
    raise SystemExit(main())
