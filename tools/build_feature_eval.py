def main() -> None:
    data = {
        "formula": [{"latex": l, "subject": s, "expect": e} for l, s, e in FORMULA],
        "text": [{"text": t, "subject": s, "qtype": "text", "expect": e}
                 for t, s, e in TEXT],
        "figure": [{"text": t, "annotation": a, "subject": s, "qtype": "figure",
                    "expect": e} for t, a, s, e in FIGURE],
        "english": [{"text": t, "annotation": a, "subject": s, "qtype": qt,
                     "expect": e} for t, a, s, qt, e in ENGLISH],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    for k, v in data.items():
        print("{:<9} {:>3} 条，标注核心特征词 {:>3} 个".format(
            k, len(v), sum(len(x["expect"]) for x in v)))
    print("输出 ->", OUT)


if __name__ == "__main__":
    main()
